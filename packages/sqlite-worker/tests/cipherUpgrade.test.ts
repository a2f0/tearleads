import { afterEach, expect, test } from "bun:test";
import {
  closeDatabase,
  deleteDatabase,
  initDatabase,
} from "../src/loadSqlite3";
import {
  mountOpfsSnapshot,
  type OpfsTreeSnapshot,
  uninstallOpfsMemoryShim,
} from "./opfsMemoryShim";

interface EncodedSnapshot {
  dirs: Record<string, EncodedSnapshot>;
  files: Record<string, string>;
}

function decode(snapshot: EncodedSnapshot): OpfsTreeSnapshot {
  return {
    dirs: Object.fromEntries(
      Object.entries(snapshot.dirs).map(([name, child]) => [
        name,
        decode(child),
      ]),
    ),
    files: Object.fromEntries(
      Object.entries(snapshot.files).map(([name, bytes]) => [
        name,
        Uint8Array.from(Buffer.from(bytes, "base64")),
      ]),
    ),
  };
}

afterEach(uninstallOpfsMemoryShim);

// Historical encrypted bytes, not a database regenerated by the current runtime.
// See fixtures/README.md for the producing artifact and public fixture key.
test("opens, updates, and reopens a SQLite3MC 2.5.1 encrypted database", async () => {
  const fixture = (await Bun.file(
    new URL("./fixtures/cipher251.json", import.meta.url),
  ).json()) as EncodedSnapshot;
  mountOpfsSnapshot(decode(fixture));
  const options = {
    dbName: "/upgrade-2.5.1.db",
    cipher: "chacha20" as const,
    persistence: "opfs-sahpool" as const,
    key: "upgrade-fixture-key",
  };
  let db = await initDatabase({ ...options, key: "wrong-fixture-key" });
  try {
    expect(() => db.selectValue("SELECT body FROM notes")).toThrow(
      "SQLITE_NOTADB",
    );
    await closeDatabase(db);
    db = await initDatabase(options);
    expect(db.selectValue("SELECT body FROM notes WHERE id=1")).toBe(
      "persisted before runtime upgrade",
    );
    expect(db.selectValue("PRAGMA integrity_check")).toBe("ok");
    db.exec("UPDATE notes SET body='updated after runtime upgrade' WHERE id=1");
    await closeDatabase(db);
    db = await initDatabase(options);
    expect(db.selectValue("SELECT body FROM notes WHERE id=1")).toBe(
      "updated after runtime upgrade",
    );
    expect(db.selectValue("PRAGMA integrity_check")).toBe("ok");
  } finally {
    await deleteDatabase(db);
  }
});
